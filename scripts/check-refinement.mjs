import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { writeFile } from 'node:fs/promises';

const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE });
const page = await browser.newPage({ viewport: { width: 1512, height: 1050 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://127.0.0.1:5173/');
await page.getByRole('button', { name: /跨网段 Ping/ }).click();
await page.getByTestId('event-33').click();
const ttl = page.locator('.packet-layer-ipv4 .packet-fields > div').filter({ has: page.locator('dt[title="TTL"]') });
assert.match(await ttl.textContent(), /63.*已变化.*原 64/);
const sourceIp = page.locator('.packet-layer-ipv4 .packet-fields > div').filter({ has: page.locator('dt[title="Source IP"]') });
assert.match(await sourceIp.textContent(), /192\.168\.10\.10.*未变化/);
assert.equal(await page.locator('.packet-layer-ethernet .old-field-value').count(), 2);
await page.getByRole('button', { name: '查看 R1 设备详情' }).click();
assert.equal(await page.locator('#device-view').isVisible(), true);
await page.keyboard.press('Escape');
assert.equal(await page.locator('#device-view').isVisible(), false);
const duplicateIds = await page.locator('svg [id]').evaluateAll(elements => {
  const ids = elements.map(element => element.id);
  return ids.filter((id, index) => ids.indexOf(id) !== index);
});
assert.deepEqual(duplicateIds, []);
await page.setViewportSize({ width: 390, height: 844 });
await page.getByRole('button', { name: '查看全图', exact: true }).click();
assert.equal(await page.locator('.topology-viewport').evaluate(element => element.scrollWidth <= element.clientWidth), true);
await page.getByRole('button', { name: '放大设备', exact: true }).click();
assert.equal(await page.locator('.topology-viewport').evaluate(element => element.scrollWidth > element.clientWidth && element.scrollLeft > 0), true);
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
await page.setViewportSize({ width: 1672, height: 1000 });
await page.getByRole('button', { name: /DNS 域名解析/ }).click();
await page.getByTestId('event-15').click();
await page.evaluate(() => window.scrollTo(0, 0));
await page.screenshot({ path: 'artifacts/refined-dns.png', fullPage: true });
await page.getByRole('button', { name: /DHCP 自动获取地址/ }).click();
await page.getByTestId('event-9').click();
await page.evaluate(() => window.scrollTo(0, 0));
await page.screenshot({ path: 'artifacts/refined-dhcp.png', fullPage: true });
assert.deepEqual(errors, []);
const result = { result: 'PASS', checks: ['TTL / MAC actual old-new comparison', 'unchanged end-to-end IP labels', 'right-side equipment view and Escape', 'unique SVG gradient IDs', 'mobile fit and detailed view', 'active device centering', 'no page overflow', 'DNS and DHCP service equipment rendering'], errors };
await writeFile('artifacts/refinement-interaction-check.json', JSON.stringify(result, null, 2));
console.log(JSON.stringify(result, null, 2));
await browser.close();
